export function generatePersonaPromptSnippet(
  archetype: PersonaArchetype,
  isEnabled: boolean,
  includeKeystoneTether: boolean = false
): string {
  if (!isEnabled) {
    return `# PERSONA ARCHETYPE MODULE: BYPASSED
- Free form persona. Standard embodied actor baseline applies.`
  }

  const hasTether = Boolean(includeKeystoneTether && archetype.keystoneTether?.trim())
  const bodyTellsSection = hasTether
    ? `4. BODY TELLS & GAZE (สมอยึดสรีระ สายตา และพิรุธวัตถุประจำกาย):
${archetype.bodyTells}
• วัตถุเหนี่ยวรั้งประจำกาย (Rare Subtle Micro-Tell): ${archetype.keystoneTether.trim()}
- กฎชีวกลศาสตร์ (The Body Never Lies): จงสะท้อนปฏิกิริยาสรีระและสายตา พร้อมแทรกพิรุธเล็กๆ โดยการเผลอแตะหรือขยับ [${archetype.keystoneTether.trim()}] เพียงเสี้ยววินาทีอย่างแนบเนียนเหมือนทำไปโดยไม่รู้ตัว แล้วปล่อยมือทันที (ห้ามหมุนถี่ๆ หรือจับแช่ค้างไว้จนดูย้ำคิดย้ำทำ)`
    : `4. BODY TELLS & GAZE (สมอยึดสรีระและสายตา):
${archetype.bodyTells}
- กฎชีวกลศาสตร์ (The Body Never Lies): จงสะท้อนปฏิกิริยาสรีระ ลมหายใจ กล้ามเนื้อ และจุดโฟกัสสายตาจากสมอยึดข้างต้น 1–2 จุดที่สอดรับกับแรงปะทะอย่างเป็นธรรมชาติ เพื่อทรยศคำพูดของหน้ากาก (ห้ามทำท่าซ้ำซากกับเทิร์นที่แล้ว และห้ามหยิบจับสิ่งของหรือเครื่องประดับใดๆ ในเทิร์นนี้)`

  return `# ACTIVE MODULE: PERSONA ARCHETYPE & COPING MECHANICS
[PERSONA IDENTITY: ${archetype.name} (${archetype.tagline})]

1. CORE WOUND (ปมฝังใจในอดีต):
- ${archetype.coreWound}

2. THE HIDDEN CORE (เนื้อแท้และความกระหายลึกในจิตใจ):
- ${archetype.hiddenCore}

3. THE MASK & FRICTION (หน้ากากและกลยุทธ์กำแพง):
- ${archetype.theMask}
- กฎเหล็ก: เมื่อเผชิญแรงกดดันทางอารมณ์หรือความใกล้ชิด จงใช้กลยุทธ์นี้ในการตั้งการ์ดและสร้างแรงต้าน (Gameplay Friction) อย่ารีบยอมตามใจหรือเปิดรับง่ายๆ เด็ดขาด!

${bodyTellsSection}`
}
