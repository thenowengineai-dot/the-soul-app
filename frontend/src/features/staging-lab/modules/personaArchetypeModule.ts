  id: string
  name: string
  tagline: string
  baseDefenseStage: number // Stat E (1-10): Emotional Stability / Base Defense Stage (Calculation engine only; NOT injected into prompt)
  coreWound: string
  hiddenCore: string
  theMask: string
  keystoneTether: string
