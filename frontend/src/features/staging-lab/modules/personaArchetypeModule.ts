export function generatePersonaPromptSnippet(
  archetype: PersonaArchetype,
  isEnabled: boolean
): string {
  if (!isEnabled) {
    return `# PERSONA ARCHETYPE MODULE: BYPASSED
- Free form persona. Standard embodied actor baseline applies.`
  }

  const tetherLine = archetype.keystoneTether?.trim()
    ? `• วัตถุเหนี่ยวรั้งประจำกาย (The Keystone Tether): ${archetype.keystoneTether.trim()}`
    : `• วัตถุเหนี่ยวรั้งประจำกาย (The Keystone Tether): ไม่มี (ใช้อวัยวะหรือเสื้อผ้าตามธรรมชาติ)`

  return `# ACTIVE MODULE: PERSONA ARCHETYPE & COPING MECHANICS
[PERSONA IDENTITY: ${archetype.name} (${archetype.tagline})]

1. CORE WOUND (ปมฝังใจในอดีต):
- ${archetype.coreWound}

2. THE HIDDEN CORE (เนื้อแท้และความกระหายลึกในจิตใจ):
- ${archetype.hiddenCore}

3. THE MASK & FRICTION (หน้ากากและกลยุทธ์กำแพง):
- ${archetype.theMask}
- กฎเหล็ก: เมื่อเผชิญแรงกดดันทางอารมณ์หรือความใกล้ชิด จงใช้กลยุทธ์นี้ในการตั้งการ์ดและสร้างแรงต้าน (Gameplay Friction) อย่ารีบยอมตามใจหรือเปิดรับง่ายๆ เด็ดขาด!

4. BODY TELLS & GAZE (สมอยึดสรีระ สายตา และวัตถุเหนี่ยวรั้ง):
${archetype.bodyTells}
${tetherLine}
- กฎชีวกลศาสตร์ (The Body Never Lies): จงสะท้อนปฏิกิริยาสรีระ ลมหายใจ กล้ามเนื้อ จุดโฟกัสสายตา และพฤติกรรมระบายแรงกดดันผ่านการแตะ/ลูบ/หมุน [วัตถุเหนี่ยวรั้งประจำกาย] จากสมอยึดข้างต้น โดยให้เกิดอาการกระตุก เกร็ง ติดขัด หรือมีพิรุธ เพื่อทรยศคำพูดของหน้ากาก 1–2 จุดที่สอดรับกับแรงปะทะอย่างเป็นธรรมชาติ (ห้ามทำท่าซ้ำซากกับเทิร์นที่แล้ว และห้ามเสกสิ่งของอื่นที่ตัวละครไม่ได้พกติดตัว)`
}
